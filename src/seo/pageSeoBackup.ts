import { PAGE_SEO_PATHS, SEO_LIMITS } from './pageSeoRegistry';
import { normaliseKeywords, robotsProblem, singleLine } from './seoFields';

/**
 * Export / restore format for page SEO (see src/scripts/page-seo.ts).
 *
 * The restore is emitted as plain SQL rather than written through the API so
 * it can be reviewed before it runs, applied to a local database first, and
 * run with whatever the operator already uses (`supabase db execute`, psql,
 * the SQL editor). It is idempotent: running it twice leaves the same rows.
 */

export interface SeoExportGroup {
  metaTitle?: string | null;
  metaDescription?: string | null;
  ogTitle?: string | null;
  ogDescription?: string | null;
  ogImage?: string | null;
  ogImageAlt?: string | null;
  keywords?: string[];
  noindex?: boolean;
  nofollow?: boolean;
  intentNote?: string | null;
}

export interface SeoExport {
  format: 'glorytecks-page-seo/1';
  exportedAt: string;
  pages: ({ path: string } & SeoExportGroup)[];
  about: SeoExportGroup | null;
  courses: { slug: string; seo: SeoExportGroup }[];
  comparisons: { slug: string; metaDescription: string }[];
}

export interface RestorePlan {
  sql: string;
  skipped: string[];
  counts: { pages: number; about: number; courses: number; comparisons: number };
}

/* ── SQL literals ─────────────────────────────────────────────────────────── */

const lit = (v: string | null | undefined) => (v === null || v === undefined ? 'null' : `'${v.replace(/'/g, "''")}'`);
const bool = (v: boolean | undefined) => (v ? 'true' : 'false');
const arr = (v: string[]) => (v.length ? `array[${v.map(lit).join(', ')}]::text[]` : `'{}'::text[]`);
const SLUG = /^[a-z0-9]+(-[a-z0-9]+)*$/;

/** Normalise one group exactly as the API would; null when a value is unusable. */
function clean(group: SeoExportGroup, where: string, skipped: string[]): Required<SeoExportGroup> | null {
  const text = (key: keyof typeof SEO_LIMITS, v: unknown): string | null => {
    if (v === null || v === undefined) return null;
    if (typeof v !== 'string') throw new Error(`${key} is not text`);
    const out = key === 'intentNote' ? v.trim() || null : singleLine(v);
    if (out && out.length > SEO_LIMITS[key]) throw new Error(`${key} is longer than ${SEO_LIMITS[key]} characters`);
    return out;
  };
  try {
    const ogImage = group.ogImage ? String(group.ogImage).trim() : null;
    if (ogImage && !/^https:\/\/\S+$/i.test(ogImage)) throw new Error('ogImage is not an https URL');
    const keywords = normaliseKeywords(Array.isArray(group.keywords) ? group.keywords : []);
    if (keywords.length > SEO_LIMITS.keywords) throw new Error('too many keywords');
    if (keywords.some((k) => k.length > SEO_LIMITS.keyword)) throw new Error('a keyword is too long');
    const out = {
      metaTitle: text('metaTitle', group.metaTitle),
      metaDescription: text('metaDescription', group.metaDescription),
      ogTitle: text('ogTitle', group.ogTitle),
      ogDescription: text('ogDescription', group.ogDescription),
      ogImage,
      ogImageAlt: text('ogImageAlt', group.ogImageAlt),
      keywords,
      noindex: Boolean(group.noindex),
      nofollow: Boolean(group.nofollow),
      intentNote: text('intentNote', group.intentNote),
    };
    const problem = robotsProblem(out);
    if (problem) throw new Error(problem);
    return out;
  } catch (err) {
    skipped.push(`${where}: ${(err as Error).message}`);
    return null;
  }
}

/** Build the restore SQL for an export. Pure: no database access. */
export function buildRestoreSql(data: SeoExport): RestorePlan {
  if (data?.format !== 'glorytecks-page-seo/1') throw new Error('Not a page SEO export (format mismatch)');
  const skipped: string[] = [];
  const lines: string[] = [
    '-- Page SEO restore, generated by src/scripts/page-seo.ts',
    `-- from an export taken ${data.exportedAt}. Idempotent; review before running.`,
    'begin;',
  ];
  const counts = { pages: 0, about: 0, courses: 0, comparisons: 0 };
  const allowed = new Set(PAGE_SEO_PATHS);

  for (const page of data.pages ?? []) {
    if (!allowed.has(page.path)) {
      skipped.push(`${page.path}: not a page_seo path in this version's registry`);
      continue;
    }
    const v = clean(page, page.path, skipped);
    if (!v) continue;
    lines.push(
      `insert into public.page_seo (path, meta_title, meta_description, og_title, og_description, og_image, og_image_alt, keywords, noindex, nofollow, intent_note)`,
      `values (${lit(page.path)}, ${lit(v.metaTitle)}, ${lit(v.metaDescription)}, ${lit(v.ogTitle)}, ${lit(v.ogDescription)}, ${lit(v.ogImage)}, ${lit(v.ogImageAlt)}, ${arr(v.keywords)}, ${bool(v.noindex)}, ${bool(v.nofollow)}, ${lit(v.intentNote)})`,
      `on conflict (path) do update set meta_title = excluded.meta_title, meta_description = excluded.meta_description, og_title = excluded.og_title, og_description = excluded.og_description, og_image = excluded.og_image, og_image_alt = excluded.og_image_alt, keywords = excluded.keywords, noindex = excluded.noindex, nofollow = excluded.nofollow, intent_note = excluded.intent_note;`,
    );
    counts.pages++;
  }

  const groupSet = (v: Required<SeoExportGroup>) =>
    `seo_meta_title = ${lit(v.metaTitle)}, seo_meta_description = ${lit(v.metaDescription)}, seo_og_title = ${lit(v.ogTitle)}, seo_og_description = ${lit(v.ogDescription)}, seo_og_image = ${lit(v.ogImage)}, seo_og_image_alt = ${lit(v.ogImageAlt)}, seo_keywords = ${arr(v.keywords)}, seo_noindex = ${bool(v.noindex)}, seo_nofollow = ${bool(v.nofollow)}, seo_intent_note = ${lit(v.intentNote)}`;

  if (data.about) {
    const v = clean(data.about, '/about', skipped);
    if (v) {
      lines.push(`update public.about_page set ${groupSet(v)};`);
      counts.about++;
    }
  }

  for (const c of data.courses ?? []) {
    if (!SLUG.test(c.slug ?? '')) {
      skipped.push(`course ${JSON.stringify(c.slug)}: not a slug`);
      continue;
    }
    const v = clean(c.seo ?? {}, `/courses/${c.slug}`, skipped);
    if (!v) continue;
    lines.push(`update public.courses set ${groupSet(v)} where slug = ${lit(c.slug)};`);
    counts.courses++;
  }

  for (const c of data.comparisons ?? []) {
    if (!SLUG.test(c.slug ?? '')) {
      skipped.push(`comparison ${JSON.stringify(c.slug)}: not a slug`);
      continue;
    }
    const d = singleLine(String(c.metaDescription ?? '')) ?? '';
    if (d.length > SEO_LIMITS.metaDescription) {
      skipped.push(`/compare/${c.slug}: metaDescription is longer than ${SEO_LIMITS.metaDescription} characters`);
      continue;
    }
    lines.push(`update public.comparisons set meta_description = ${lit(d)} where slug = ${lit(c.slug)};`);
    counts.comparisons++;
  }

  lines.push('commit;', '');
  return { sql: lines.join('\n'), skipped, counts };
}
